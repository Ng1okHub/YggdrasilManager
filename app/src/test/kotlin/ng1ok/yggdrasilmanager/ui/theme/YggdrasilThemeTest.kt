package ng1ok.yggdrasilmanager.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Test

class YggdrasilThemeTest {
    @Test
    fun lightThemeUsesApprovedSemanticColors() {
        val scheme = yggdrasilColorScheme(darkTheme = false)
        assertEquals(Color(0xFF006C4C), scheme.primary)
        assertEquals(Color(0xFFFFFFFF), scheme.onPrimary)
        assertEquals(Color(0xFF8CF8C6), scheme.primaryContainer)
        assertEquals(Color(0xFF002116), scheme.onPrimaryContainer)
        assertEquals(Color(0xFF52645C), scheme.secondary)
        assertEquals(Color(0xFFFFFFFF), scheme.onSecondary)
        assertEquals(Color(0xFFD5E8DE), scheme.secondaryContainer)
        assertEquals(Color(0xFF0F1F18), scheme.onSecondaryContainer)
        assertEquals(Color(0xFF53606F), scheme.tertiary)
        assertEquals(Color(0xFFFFFFFF), scheme.onTertiary)
        assertEquals(Color(0xFFD7E4F7), scheme.tertiaryContainer)
        assertEquals(Color(0xFF101C2B), scheme.onTertiaryContainer)
        assertEquals(Color(0xFFBA1A1A), scheme.error)
        assertEquals(Color(0xFFFFFFFF), scheme.onError)
        assertEquals(Color(0xFFFFDAD6), scheme.errorContainer)
        assertEquals(Color(0xFF410002), scheme.onErrorContainer)
        assertEquals(Color(0xFFF7F9FA), scheme.background)
        assertEquals(Color(0xFF191C1D), scheme.onBackground)
        assertEquals(Color(0xFFF7F9FA), scheme.surface)
        assertEquals(Color(0xFF191C1D), scheme.onSurface)
        assertEquals(Color(0xFFE0E3E6), scheme.surfaceVariant)
        assertEquals(Color(0xFF44474A), scheme.onSurfaceVariant)
        assertEquals(Color(0xFF74777A), scheme.outline)
        assertEquals(Color(0xFFC4C7CA), scheme.outlineVariant)
        assertEquals(Color(0xFF2E3132), scheme.inverseSurface)
        assertEquals(Color(0xFFEFF1F2), scheme.inverseOnSurface)
        assertEquals(Color(0xFF6DDBAD), scheme.inversePrimary)
        assertEquals(Color(0xFFF7F9FA), scheme.surfaceBright)
        assertEquals(Color(0xFFD8DADB), scheme.surfaceDim)
        assertEquals(Color(0xFFFFFFFF), scheme.surfaceContainerLowest)
        assertEquals(Color(0xFFF1F3F4), scheme.surfaceContainerLow)
        assertEquals(Color(0xFFEBEDEF), scheme.surfaceContainer)
        assertEquals(Color(0xFFE5E7E9), scheme.surfaceContainerHigh)
        assertEquals(Color(0xFFDFE1E3), scheme.surfaceContainerHighest)
        assertEquals(Color(0xFF006C4C), scheme.surfaceTint)
        assertEquals(Color(0xFF000000), scheme.scrim)
        assertNotEquals(scheme.primary, scheme.error)
    }

    @Test
    fun darkThemeAndShapesUseApprovedTokens() {
        val scheme = yggdrasilColorScheme(darkTheme = true)
        assertEquals(Color(0xFF6DDBAD), scheme.primary)
        assertEquals(Color(0xFF003828), scheme.onPrimary)
        assertEquals(Color(0xFF00513A), scheme.primaryContainer)
        assertEquals(Color(0xFF8CF8C6), scheme.onPrimaryContainer)
        assertEquals(Color(0xFFB8CCC1), scheme.secondary)
        assertEquals(Color(0xFF24352D), scheme.onSecondary)
        assertEquals(Color(0xFF3B4B43), scheme.secondaryContainer)
        assertEquals(Color(0xFFD5E8DE), scheme.onSecondaryContainer)
        assertEquals(Color(0xFFBBC7DB), scheme.tertiary)
        assertEquals(Color(0xFF253140), scheme.onTertiary)
        assertEquals(Color(0xFF3B4858), scheme.tertiaryContainer)
        assertEquals(Color(0xFFD7E4F7), scheme.onTertiaryContainer)
        assertEquals(Color(0xFFFFB4AB), scheme.error)
        assertEquals(Color(0xFF690005), scheme.onError)
        assertEquals(Color(0xFF93000A), scheme.errorContainer)
        assertEquals(Color(0xFFFFDAD6), scheme.onErrorContainer)
        assertEquals(Color(0xFF101416), scheme.background)
        assertEquals(Color(0xFFE0E3E4), scheme.onBackground)
        assertEquals(Color(0xFF101416), scheme.surface)
        assertEquals(Color(0xFFE0E3E4), scheme.onSurface)
        assertEquals(Color(0xFF44474A), scheme.surfaceVariant)
        assertEquals(Color(0xFFC4C7CA), scheme.onSurfaceVariant)
        assertEquals(Color(0xFF8E9194), scheme.outline)
        assertEquals(Color(0xFF44474A), scheme.outlineVariant)
        assertEquals(Color(0xFFE0E3E4), scheme.inverseSurface)
        assertEquals(Color(0xFF2E3132), scheme.inverseOnSurface)
        assertEquals(Color(0xFF006C4C), scheme.inversePrimary)
        assertEquals(Color(0xFF363A3C), scheme.surfaceBright)
        assertEquals(Color(0xFF101416), scheme.surfaceDim)
        assertEquals(Color(0xFF0B0F10), scheme.surfaceContainerLowest)
        assertEquals(Color(0xFF191C1E), scheme.surfaceContainerLow)
        assertEquals(Color(0xFF1D2022), scheme.surfaceContainer)
        assertEquals(Color(0xFF272A2C), scheme.surfaceContainerHigh)
        assertEquals(Color(0xFF323537), scheme.surfaceContainerHighest)
        assertEquals(Color(0xFF6DDBAD), scheme.surfaceTint)
        assertEquals(Color(0xFF000000), scheme.scrim)
        assertEquals(RoundedCornerShape(8.dp), YggdrasilShapes.medium)
        assertEquals(RoundedCornerShape(8.dp), YggdrasilShapes.large)
    }
}
