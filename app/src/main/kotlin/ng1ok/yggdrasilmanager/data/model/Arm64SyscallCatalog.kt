package ng1ok.yggdrasilmanager.data.model

/**
 * How a syscall number behaves on the device the Manager is talking to.
 *
 * [ARCH_UNSUPPORTED] and [KERNEL_DISABLED] both mean "selecting this will never
 * produce an event", but for different reasons, so the picker labels them apart.
 */
enum class SyscallAvailability(
    val wireName: String,
) {
    /** The kernel implements the syscall. */
    AVAILABLE("available"),

    /** Defined by the arm64 ABI but the running kernel was built without it. */
    KERNEL_DISABLED("kernel_disabled"),

    /** No arm64 implementation exists at all (reserved or permanently removed). */
    ARCH_UNSUPPORTED("arch_unsupported"),
}

/** One row of the syscall picker. */
data class Arm64SyscallEntry(
    val nr: Int,
    val name: String,
    val availability: SyscallAvailability,
    /** True when the KPM parses this syscall's arguments automatically. */
    val hasArgumentSchema: Boolean,
    /** True when only the enter phase can be observed (exit/exit_group). */
    val enterOnly: Boolean,
)

