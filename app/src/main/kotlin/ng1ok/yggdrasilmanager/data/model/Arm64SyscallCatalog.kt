    /** Reserved here on every arm64 kernel: 244 is `arch_specific_syscall`. */
    private val archUnsupported: Set<Int> =
        setOf(42) + (244..259)

    /** Present in the ABI but compiled out of this kernel build. */
    private val kernelDisabled: Set<Int> =
        setOf(89, 104) + (180..197) + (235..239) + (262..265) + (288..290)

    /** A task that calls these never returns, so only the enter phase is observable. */
    private val enterOnly: Set<Int> = setOf(93, 94)

    /** True when a rule may only observe the enter phase. */
    fun isEnterOnly(syscallNr: Int): Boolean = syscallNr in enterOnly

    fun nameFor(syscallNr: Int): String = names[syscallNr] ?: "syscall_$syscallNr"

    fun availabilityOf(syscallNr: Int): SyscallAvailability = when (syscallNr) {
        in archUnsupported -> SyscallAvailability.ARCH_UNSUPPORTED
        in kernelDisabled -> SyscallAvailability.KERNEL_DISABLED
        else -> SyscallAvailability.AVAILABLE
    }

    /** Catalog rows in picker order: observable syscalls first, then the rest. */
    fun entries(argumentSchemaNumbers: Set<Int>): List<Arm64SyscallEntry> =
        (SELECTOR_FIRST..SELECTOR_LAST)
            .map { syscallNr ->
                Arm64SyscallEntry(
                    nr = syscallNr,
                    name = nameFor(syscallNr),
                    availability = availabilityOf(syscallNr),
                    hasArgumentSchema = syscallNr in argumentSchemaNumbers,
                    enterOnly = isEnterOnly(syscallNr),
                )
            }
            .sortedWith(compareBy({ it.availability.ordinal }, { it.nr }))
}
